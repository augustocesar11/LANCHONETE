//Programa para dizer o dia da semana
//1 - Domingo, 2- Segunda ...

//Estrutura Switch Case - Escolha caso

let dia = 3

switch (dia) {
    case 1:
        console.log("Domingo")
        break;
    case 2:
        console.log("Segunda")
        break;
    case 3:
        console.log("Terça")
        break;
    case 4:
        console.log("Quarta")
        break;
    case 5:
        console.log("Quinta")
        break;
    case 6:
        console.log("Sexta")
        break;
    case 7:
        console.log("Sabádo")
        break;

    default:
        console.log("Código inválido")
        break;
}
